"""Generate the short original cheer used by both listen-and-pick games.

This is a synthesized UI chime, not a field recording and not a voice.
FFmpeg/libopus encodes it as mono 24 kHz CBR Ogg Opus with 60 ms packets,
matching the local-interaction playback limits. No network access.
"""

import argparse
import math
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_animal_sounds import ogg_packets, packet_duration_ms

BOARD = Path(__file__).resolve().parents[1]
HEADER = BOARD / "listen_pick_cheer.h"
SAMPLE_RATE = 24000
DURATION_S = 0.54


def samples():
    count = int(SAMPLE_RATE * DURATION_S)
    notes = (
        (0.00, 0.22, 523.25),  # C5
        (0.16, 0.38, 659.25),  # E5
        (0.32, 0.54, 783.99),  # G5
    )
    rendered = []
    for index in range(count):
        t = index / SAMPLE_RATE
        value = 0.0
        for start, end, frequency in notes:
            if t < start or t >= end:
                continue
            attack = min(1.0, (t - start) / 0.015)
            release = min(1.0, (end - t) / 0.07)
            envelope = max(0.0, min(attack, release))
            phase = 2.0 * math.pi * frequency * t
            # A little second harmonic keeps the chime from sounding like a buzzer.
            value += envelope * (math.sin(phase) + 0.18 * math.sin(2.0 * phase))
        rendered.append(value)
    peak = max(abs(value) for value in rendered)
    # About -10 dBFS, softer than the -7 dBFS game recordings.
    gain = (32767 * 10 ** (-10 / 20)) / peak
    return b"".join(
        struct.pack("<h", max(-32767, min(32767, int(value * gain)))) for value in rendered
    )


def encode(pcm, destination):
    subprocess.run(
        [
            "ffmpeg", "-v", "error", "-y", "-fflags", "+bitexact",
            "-f", "s16le", "-ar", str(SAMPLE_RATE), "-ac", "1", "-i", "pipe:0",
            "-map_metadata", "-1", "-c:a", "libopus", "-b:a", "24000", "-vbr", "off",
            "-application", "audio", "-frame_duration", "60", "-compression_level", "10",
            "-flags:a", "+bitexact", "-fflags", "+bitexact", "-serial_offset", "0",
            "-metadata", "comment=Original synthesized listen-and-pick cheer",
            str(destination),
        ],
        input=pcm, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
    )


def header_text(ogg):
    rows = [
        "    " + ", ".join(f"0x{byte:02x}" for byte in ogg[i:i + 16]) + ","
        for i in range(0, len(ogg), 16)
    ]
    body = "\n".join(rows)
    return f"""// Generated by tools/generate_listen_pick_cheer.py. Do not edit by hand.
// Original synthesized UI chime (MIT). Not a recording and not a voice.
#pragma once
#include <cstddef>
#include <string_view>

namespace listen_pick_cheer {{

// clang-format off
inline constexpr unsigned char kOgg[] = {{
{body}
}};
// clang-format on

inline std::string_view Get() {{
    return {{reinterpret_cast<const char*>(kOgg), sizeof(kOgg)}};
}}

}}  // namespace listen_pick_cheer
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as temporary:
        ogg_path = Path(temporary) / "cheer.ogg"
        encode(samples(), ogg_path)
        ogg = ogg_path.read_bytes()
        packets = ogg_packets(ogg)
        if packets[0][:8] != b"OpusHead" or packets[0][9] != 1:
            raise SystemExit("Cheer must be mono Opus")
        if struct.unpack_from("<I", packets[0], 12)[0] != SAMPLE_RATE:
            raise SystemExit("Cheer must be 24 kHz")
        if any(packet_duration_ms(packet) != 60 for packet in packets[2:]):
            raise SystemExit("Cheer packets must be 60 ms")
        playback_ms = len(packets[2:]) * 60
        if not 300 <= playback_ms <= 1000 or len(ogg) > 8 * 1024:
            raise SystemExit(f"Cheer length out of range: {playback_ms} ms, {len(ogg)} bytes")
        text = header_text(ogg)
    if args.check:
        if not HEADER.exists() or HEADER.read_text() != text:
            raise SystemExit("Cheer header differs; regenerate without --check")
        print("Listen-and-pick cheer matches")
        return
    HEADER.write_text(text)
    print(f"Wrote {HEADER.name}: {HEADER.stat().st_size} bytes")


if __name__ == "__main__":
    sys.exit(main())
