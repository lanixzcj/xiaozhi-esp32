"""Generate flash-resident LVGL RGB565 cards from attributed real photographs.

Requires Pillow. Source JPEG files and provenance are committed alongside the
firmware. Only technical crop/resize/color conversion is applied, matching the
preview's CSS object-fit: cover and object-position. No AI generation or retouch.
Photo pixels retain their individual licenses; this script alone is MIT.
"""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageOps

BOARD = Path(__file__).resolve().parents[1]
SOURCE = BOARD / "assets/photos"
NAMES = ("cat", "dog", "duck", "chicken", "cow", "sheep")
WIDTH, HEIGHT = 296, 162


def render():
    sources = json.loads((SOURCE / "provenance.json").read_text())
    metadata = {entry["animal"]: entry for entry in sources}
    header = ["// Generated descriptors; photo pixels retain licenses in ANIMAL_PHOTO_ASSETS.md.",
              "#pragma once", '#include "sdkconfig.h"',
              "#ifndef CONFIG_USE_EMOTE_MESSAGE_STYLE", "#include <stddef.h>",
              '#include "lvgl.h"', "#ifdef __cplusplus", 'extern "C" {', "#endif",
              "const lv_image_dsc_t* animal_game_photo(size_t index);",
              "#ifdef __cplusplus", "}", "#endif", "#endif", ""]
    output = ["// Generated by tools/generate_animal_photos.py. Do not edit by hand.",
              "// Each photo retains its own license. See ANIMAL_PHOTO_ASSETS.md.",
              '#include "animal_game_photos.h"', "#ifndef CONFIG_USE_EMOTE_MESSAGE_STYLE", ""]
    reports = []
    for name in NAMES:
        entry = metadata[name]
        source = SOURCE / (name + ".jpg")
        digest = hashlib.sha256(source.read_bytes()).hexdigest()
        if digest != entry["sha256"]:
            raise ValueError(name + ": source SHA-256 mismatch")
        position = entry.get("css_object_position", "50% 50%")
        center = tuple(float(value.rstrip("%")) / 100 for value in position.split())
        with Image.open(source) as original:
            rgb = original.convert("RGB")
            if "source_crop" in entry:
                rgb = rgb.crop(tuple(entry["source_crop"]))
            if entry.get("css_object_fit", "cover") == "contain":
                fitted = ImageOps.contain(rgb, (WIDTH, HEIGHT), Image.Resampling.LANCZOS)
                image = Image.new("RGB", (WIDTH, HEIGHT), "#eee6d7")
                image.paste(fitted, (round((WIDTH - fitted.width) * center[0]),
                                     round((HEIGHT - fitted.height) * center[1])))
            else:
                # ImageOps.fit uses the same proportional crop anchor as CSS cover.
                image = ImageOps.fit(rgb, (WIDTH, HEIGHT),
                                     method=Image.Resampling.LANCZOS, centering=center)
        raw = bytearray()
        for red, green, blue in image.getdata():
            pixel = ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)
            raw.extend((pixel & 255, pixel >> 8))
        symbol = "photo_" + name
        output += ["// " + entry["creator"] + " / " + entry["license"],
                   "// clang-format off",
                   "static const LV_ATTRIBUTE_MEM_ALIGN uint8_t " + symbol + "_data[] = {"]
        for offset in range(0, len(raw), 16):
            output.append("    " + ", ".join(f"0x{byte:02x}" for byte in raw[offset:offset+16]) + ",")
        output += ["};", "static const lv_image_dsc_t " + symbol + " = {",
                   "    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565,",
                   f"               .w = {WIDTH}, .h = {HEIGHT}, .stride = {WIDTH * 2}}},",
                   "    .data_size = sizeof(" + symbol + "_data),",
                   "    .data = " + symbol + "_data,", "};", "// clang-format on", ""]
        reports.append({"animal": name, "source_sha256": digest,
                        "rgb565_sha256": hashlib.sha256(raw).hexdigest(),
                        "width": WIDTH, "height": HEIGHT, "bytes": len(raw),
                        "source_crop": entry.get("source_crop"),
                        "css_object_position": position, "css_object_fit": entry.get("css_object_fit", "cover"),
                        "license": entry["license"],
                        "processing": "LANCZOS aspect-preserving " + entry.get("css_object_fit", "cover") + " resize/crop to 296x162; little-endian RGB565. No retouch."})
    output += ["const lv_image_dsc_t* animal_game_photo(size_t index) {",
               "    static const lv_image_dsc_t* const images[] = {" +
               ", ".join("&photo_" + n for n in NAMES) + "};",
               "    return index < sizeof(images) / sizeof(images[0]) ? images[index] : NULL;",
               "}", "#endif", ""]
    return {"animal_game_photos.h": "\n".join(header),
            "animal_game_photos.c": "\n".join(output),
            "assets/photos/processing.json": json.dumps(reports, ensure_ascii=False, indent=2) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in render().items():
        path = BOARD / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit("Regenerate " + name)
        else:
            path.write_text(content)
    print("Six photo cards verified" if args.check else "Generated six photo cards (575424 flash bytes)")


if __name__ == "__main__":
    main()
