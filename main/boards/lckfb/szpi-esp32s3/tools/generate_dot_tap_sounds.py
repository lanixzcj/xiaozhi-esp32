"""Generate the original chimes for the flat-dot game.

Synthesized UI tones, not a recording and not a voice. FFmpeg/libopus encodes
each one as mono 24 kHz CBR Ogg Opus with 60 ms packets, within the local
interaction playback limits. No network access.
"""

import argparse
import math
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_animal_sounds import ogg_packets, packet_duration_ms

BOARD = Path(__file__).resolve().parents[1]
HEADER = BOARD / "dot_tap_sounds.h"
SAMPLE_RATE = 24000
# About -12 dBFS so a tap stays softer than the listen-and-pick cheer.
TARGET_PEAK = 32767 * 10 ** (-12 / 20)

CUES = (
    ("kYellow", "Yellow", 0.24),
    ("kRed", "Red", 0.24),
    ("kBlue", "Blue", 0.24),
    ("kScatter", "Scatter", 0.36),
    ("kSettle", "Settle", 0.42),
)


def envelope(t, start, end, attack=0.012, release=0.06):
    if t < start or t >= end:
        return 0.0
    return max(0.0, min((t - start) / attack, (end - t) / release, 1.0))


def render(name, duration):
    count = int(SAMPLE_RATE * duration)
    values = []
    phase = 0.0
    noise = 0x1234567
    for index in range(count):
        t = index / SAMPLE_RATE
        sample = 0.0
        if name == "Yellow":
            sample = envelope(t, 0.0, duration) * (
                math.sin(2 * math.pi * 659.25 * t) + 0.16 * math.sin(2 * math.pi * 1318.5 * t)
            )
        elif name == "Red":
            sample = envelope(t, 0.0, duration) * (
                math.sin(2 * math.pi * 523.25 * t) + 0.14 * math.sin(2 * math.pi * 784.0 * t)
            )
        elif name == "Blue":
            sample = envelope(t, 0.0, duration) * (
                math.sin(2 * math.pi * 987.77 * t) + 0.12 * math.sin(2 * math.pi * 1479.98 * t)
            )
        elif name == "Scatter":
            # A short downward slide, not a buzzer.
            freq = 880.0 + (320.0 - 880.0) * (t / duration)
            phase += 2 * math.pi * freq / SAMPLE_RATE
            noise = (1103515245 * noise + 12345) & 0x7FFFFFFF
            hiss = ((noise / 0x7FFFFFFF) * 2.0 - 1.0) * 0.08
            sample = envelope(t, 0.0, duration, 0.01, 0.09) * (math.sin(phase) + hiss)
        else:
            notes = ((0.00, 0.16, 523.25), (0.12, 0.28, 659.25), (0.24, 0.42, 783.99))
            for start, end, freq in notes:
                gain = envelope(t, start, end, 0.01, 0.05)
                sample += gain * (
                    math.sin(2 * math.pi * freq * t) + 0.12 * math.sin(4 * math.pi * freq * t)
                )
        values.append(sample)
    peak = max(abs(value) for value in values)
    if peak <= 0:
        raise SystemExit(f"{name} is silent")
    gain = TARGET_PEAK / peak
    return b"".join(
        struct.pack("<h", max(-32767, min(32767, int(value * gain)))) for value in values
    )


def encode(pcm, destination, comment):
    subprocess.run(
        [
            "ffmpeg", "-v", "error", "-y", "-fflags", "+bitexact",
            "-f", "s16le", "-ar", str(SAMPLE_RATE), "-ac", "1", "-i", "pipe:0",
            "-map_metadata", "-1", "-c:a", "libopus", "-b:a", "24000", "-vbr", "off",
            "-application", "audio", "-frame_duration", "60", "-compression_level", "10",
            "-flags:a", "+bitexact", "-fflags", "+bitexact", "-serial_offset", "0",
            "-metadata", f"comment={comment}",
            str(destination),
        ],
        input=pcm, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
    )


def validate(name, ogg, duration):
    packets = ogg_packets(ogg)
    if packets[0][:8] != b"OpusHead" or packets[0][9] != 1:
        raise SystemExit(f"{name} must be mono Opus")
    if struct.unpack_from("<I", packets[0], 12)[0] != SAMPLE_RATE:
        raise SystemExit(f"{name} must be 24 kHz")
    if any(packet_duration_ms(packet) != 60 for packet in packets[2:]):
        raise SystemExit(f"{name} packets must be 60 ms")
    playback_ms = len(packets[2:]) * 60
    expect = int(duration * 1000)
    if not expect <= playback_ms <= expect + 60 or len(ogg) > 6 * 1024:
        raise SystemExit(f"{name} length out of range: {playback_ms} ms, {len(ogg)} bytes")
    return playback_ms


def header_text(sounds):
    chunks = []
    for symbol, _name, ogg in sounds:
        rows = [
            "    " + ", ".join(f"0x{byte:02x}" for byte in ogg[i:i + 16]) + ","
            for i in range(0, len(ogg), 16)
        ]
        chunks.append(f"inline constexpr unsigned char {symbol}[] = {{\n" + "\n".join(rows) + "\n};")
    body = "\n\n".join(chunks)
    return f"""// Generated by tools/generate_dot_tap_sounds.py. Do not edit by hand.
// Original synthesized UI chimes (MIT). Not recordings and not a voice.
#pragma once
#include <cstddef>
#include <string_view>

namespace dot_tap_sounds {{

enum class Cue {{ Yellow, Red, Blue, Scatter, Settle }};

// clang-format off
{body}
// clang-format on

inline std::string_view Get(Cue cue) {{
    const unsigned char* data = kYellow;
    size_t size = sizeof(kYellow);
    switch (cue) {{
        case Cue::Yellow: break;
        case Cue::Red: data = kRed; size = sizeof(kRed); break;
        case Cue::Blue: data = kBlue; size = sizeof(kBlue); break;
        case Cue::Scatter: data = kScatter; size = sizeof(kScatter); break;
        case Cue::Settle: data = kSettle; size = sizeof(kSettle); break;
    }}
    return {{reinterpret_cast<const char*>(data), size}};
}}

}}  // namespace dot_tap_sounds
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    encoded = []
    with tempfile.TemporaryDirectory() as temporary:
        root = Path(temporary)
        for symbol, name, duration in CUES:
            path = root / f"{name}.ogg"
            encode(render(name, duration), path, f"Original synthesized dot-tap {name} chime")
            ogg = path.read_bytes()
            playback_ms = validate(name, ogg, duration)
            print(f"{name}: {playback_ms} ms, {len(ogg)} bytes")
            encoded.append((symbol, name, ogg))
        text = header_text(encoded)
    if args.check:
        if not HEADER.exists() or HEADER.read_text() != text:
            raise SystemExit("Dot-tap sound header differs; regenerate without --check")
        print("Dot-tap sounds match")
    else:
        HEADER.write_text(text)
        print(f"Wrote {HEADER.name}")


if __name__ == "__main__":
    main()
