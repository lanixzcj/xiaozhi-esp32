"""Original flat vector scenes -> reproducible opaque LVGL I4 images.

Pillow 11.1.0; no network. SVG previews and C++ pixels share the same scene
primitives. A 16-color palette keeps three 296x162 images to 77,592 flash bytes, including native-size previews.
"""
import argparse
from pathlib import Path
import struct
from PIL import Image, ImageDraw
BOARD = Path(__file__).resolve().parents[1]
PALETTE = ['FFF8EA','44382F','EF6558','FFCA4C','73B57D','A8DAE9','FFFFFF','EAB048',
           'E89887','659FC8','333D4B','EEE4D0','A58154','FFDCC0','C3DB99','D9EDF4']
# rect/ellipse/polygon: bounds/points, fill palette index, outline index, thickness.
SCENES = [
 ('apple', [
  ('rect',(143,12,154,48),12,1,4,4),
  ('ellipse',(153,14,200,37),4,1,4),
  ('polygon',[(148,46),(128,30),(97,28),(69,44),(54,70),(58,112),(82,142),
              (115,149),(148,142),(181,149),(214,142),(238,112),(242,70),
              (227,44),(199,28),(168,30)],2,1,5),
  ('ellipse',(82,50,99,78),13,None,0),
 ]),
 ('bus', [
  ('rect',(18,34,278,133),3,1,5,20),
  ('rect',(32,48,89,93),5,1,4,8),
  ('rect',(101,48,158,93),5,1,4,8),
  ('rect',(170,48,227,93),5,1,4,8),
  ('rect',(239,48,264,112),15,1,4,5),
  ('rect',(22,105,230,119),2,None,0,3),
  ('ellipse',(49,111,99,158),10,1,4),
  ('ellipse',(197,111,247,158),10,1,4),
  ('ellipse',(64,125,84,145),6,None,0),
  ('ellipse',(212,125,232,145),6,None,0),
 ]),
 ('fish', [
  ('polygon',[(20,38),(101,84),(20,140)],3,1,5),
  ('ellipse',(64,25,277,148),7,1,5),
  ('polygon',[(136,83),(178,111),(136,130)],3,1,4),
  ('ellipse',(224,58,243,77),1,None,0),
  ('ellipse',(228,60,234,66),6,None,0),
  ('ellipse',(249,86,258,95),2,None,0),
 ])]

def generate():
    parts=['// Generated by tools/generate_puzzle_assets.py; original vector art, MIT.',
           '#include "puzzle_game_assets.h"','#ifndef CONFIG_USE_EMOTE_MESSAGE_STYLE',
           'namespace puzzle_game_assets {','namespace {']
    previews={}
    for name, shapes in SCENES:
        image=Image.new('P',(296,162),0)
        palette=[int(c[i:i+2],16) for c in PALETTE for i in (0,2,4)]
        image.putpalette(palette+[0]*(768-len(palette)))
        draw=ImageDraw.Draw(image)
        svg=['<svg xmlns="http://www.w3.org/2000/svg" width="296" height="162" viewBox="0 0 296 162">',
             '<rect width="296" height="162" fill="#FFF8EA"/>']
        for shape in shapes:
            kind, points, fill, outline, width, *radius=shape
            opts=dict(fill=fill,outline=outline,width=width)
            style=f'fill="#{PALETTE[fill]}" stroke="'+('none' if outline is None else '#'+PALETTE[outline])+f'" stroke-width="{width}" stroke-linejoin="round"'
            if kind=='rect':
                draw.rounded_rectangle(points,radius=radius[0],**opts)
                x,y,r,b=points;svg.append(f'<rect x="{x}" y="{y}" width="{r-x}" height="{b-y}" rx="{radius[0]}" {style}/>')
            elif kind=='ellipse':
                draw.ellipse(points,**opts)
                x,y,r,b=points;svg.append(f'<ellipse cx="{(x+r)/2}" cy="{(y+b)/2}" rx="{(r-x)/2}" ry="{(b-y)/2}" {style}/>')
            else:
                draw.polygon(points,**opts)
                svg.append('<polygon points="'+' '.join(f'{x},{y}' for x,y in points)+f'" {style}/>')
        previews[name]='\n'.join(svg+['</svg>'])+'\n'
        for symbol, bitmap in [(name,image),(name+'_preview',image.resize((80,44),Image.Resampling.NEAREST))]:
            pixels=list(bitmap.getdata());assert max(pixels)<16
            width,height=bitmap.size
            raw=bytes(b for c in PALETTE for b in (int(c[4:6],16),int(c[2:4],16),int(c[0:2],16),255))
            raw+=bytes((pixels[i]<<4)|pixels[i+1] for i in range(0,len(pixels),2))
            assert len(raw)==64+width*height//2
            parts+=['// clang-format off',f'alignas(4) constexpr uint8_t {symbol}_pixels[] = {{']
            parts+=['    '+','.join(f'0x{x:02x}' for x in raw[i:i+24])+',' for i in range(0,len(raw),24)]
            parts+=['};','// clang-format on',f"""constexpr lv_image_dsc_t Make_{symbol}() {{
    lv_image_dsc_t d{{}};
    d.header.magic = LV_IMAGE_HEADER_MAGIC;
    d.header.cf = LV_COLOR_FORMAT_I4;
    d.header.w = {width}; d.header.h = {height}; d.header.stride = {width//2};
    d.data_size = sizeof({symbol}_pixels); d.data = {symbol}_pixels;
    return d;
}}
constexpr auto {symbol}_image = Make_{symbol}();"""]
    parts+=['}  // namespace','const lv_image_dsc_t* GetImage(size_t index) {',
            '    constexpr const lv_image_dsc_t* images[] = {&apple_image, &bus_image, &fish_image};',
            '    return index < kCount ? images[index] : nullptr;',
            '}',
            'const lv_image_dsc_t* GetPreview(size_t index) {',
            '    constexpr const lv_image_dsc_t* images[] = {&apple_preview_image, &bus_preview_image, &fish_preview_image};',
            '    return index < kCount ? images[index] : nullptr;',
            '}', '}  // namespace puzzle_game_assets','#endif','']
    return '\n'.join(parts),previews

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    code,previews=generate()
    files={BOARD/'puzzle_game_assets.cc':code}
    files.update({BOARD/'assets/puzzle'/f'{name}.svg':svg for name,svg in previews.items()})
    for path,text in files.items():
        if args.check:
            assert path.read_text()==text,f'{path.name} differs'
        else:path.write_text(text)
    print('Original puzzle vectors and I4 pixels match' if args.check else 'Generated apple, bus and fish; 77592 pixel/palette bytes, including native previews')
if __name__=='__main__':main()
