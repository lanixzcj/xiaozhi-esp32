#!/usr/bin/env python3
"""Generate the 52px offline clock digits. Same OFL source as animal_game_font."""
import argparse,subprocess,tempfile
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('font');p.add_argument('--converter',required=True);p.add_argument('--check',action='store_true');a=p.parse_args()
with tempfile.TemporaryDirectory() as t:
    out=Path(t)/'clock_digits_font.c'
    subprocess.run([a.converter,'--font',a.font,'--symbols','0123456789:-','--size','52','--bpp','4','--format','lvgl','--no-compress','--no-kerning','--lv-include','lvgl.h','--lv-font-name','clock_digits_font','-o',str(out)],check=True)
    text=out.read_text();text=text[text.index('#ifdef LV_LVGL_H_INCLUDE_SIMPLE'):]
    text='/* Generated by tools/generate_clock_font.py. Noto Sans CJK SC Regular 2.004.\n * Original font copyright (c) 2014-2021 Adobe. SIL OFL 1.1; see licenses/animal_game_font-OFL.txt.\n * Modified font name: Clock Digits UI. */\n#include "sdkconfig.h"\n#ifndef CONFIG_USE_EMOTE_MESSAGE_STYLE\n'+text+'\n#endif\n'
    dest=Path(__file__).resolve().parents[1]/'clock_digits_font.c'
    if a.check:assert dest.read_text()==text
    else:dest.write_text(text)
print('Clock digits font matches' if a.check else 'Generated clock digits font')
