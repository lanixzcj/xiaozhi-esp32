"""Offline reproducible RGB565 and real-recording Opus asset conversion.

Requires Pillow, Inkscape and FFmpeg/libopus. No network access. --check verifies
committed outputs. Source attribution and exact excerpts: assets/transport/README.md.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import tempfile
from PIL import Image
from generate_animal_sounds import ogg_packets, packet_duration_ms

BOARD = Path(__file__).resolve().parents[1]
ROOT = BOARD / 'assets/transport'
ITEMS = (
    ('Car', 'car-141901.png', 'car-real-0258.wav', 0, 1.607),
    ('Train', 'train-modern.svg', 'train-modern-2846.wav', 0, 2.4),
    ('Bicycle', 'bicycle-169493.png', 'bicycle-1042.wav', 0, 1.955),
    ('Plane', 'airplane-small-324034.png', 'airplane-0501.wav', 1, 2.5),
)
HEADER = '''// Generated by tools/generate_transport_assets.py; see assets/transport/README.md.
#pragma once
#include "sdkconfig.h"
#ifndef CONFIG_USE_EMOTE_MESSAGE_STYLE
#include <lvgl.h>
#include <cstddef>
#include <string_view>
namespace transport_game_assets {
inline constexpr size_t kCount = 4;
inline constexpr int kImageWidth = 140;
inline constexpr int kImageHeight = 130;
// Order: car, modern train, bicycle, propeller plane. Flash-resident assets.
// Invalid indices return nullptr / an empty view.
const lv_image_dsc_t* GetImage(size_t index);
std::string_view GetSound(size_t index);
}  // namespace transport_game_assets
#endif
'''

def run(args):
    return subprocess.run(args, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE).stdout

def array(name, data):
    return '\n'.join(['// clang-format off', f'alignas(4) constexpr unsigned char {name}[] = {{'] +
        ['    ' + ', '.join(f'0x{x:02x}' for x in data[i:i+16]) + ',' for i in range(0,len(data),16)] +
        ['};', '// clang-format on'])

def generate(tmp):
    parts = ['// Generated by tools/generate_transport_assets.py. Do not edit.',
        '// Wrapper: MIT. Images/audio: CC0; see assets/transport/README.md.',
        '#include "transport_game_assets.h"', '#ifndef CONFIG_USE_EMOTE_MESSAGE_STYLE',
        'namespace transport_game_assets {', 'namespace {']
    reports = []
    for name, picture, sound, start, duration in ITEMS:
        src = ROOT / 'originals' / picture
        if src.suffix == '.svg':
            dest = tmp / f'{name}.png'
            run(['inkscape', str(src), '--export-type=png', '--export-width=560', '-o', str(dest)])
            src = dest
        im = Image.open(src).convert('RGBA')
        im.thumbnail((132,122), Image.Resampling.LANCZOS)
        canvas = Image.new('RGBA',(140,130),(255,248,234,255))
        canvas.alpha_composite(im,((140-im.width)//2,(130-im.height)//2))
        canvas = canvas.convert('RGB')
        canvas.save(tmp / f'{name.lower()}.png')
        pixels = b''.join(struct.pack('<H', ((r>>3)<<11)|((g>>2)<<5)|(b>>3)) for r,g,b in canvas.get_flattened_data())
        parts.append(array(f'k{name}Pixels', pixels))
        parts.append(f"""constexpr lv_image_dsc_t Make{name}Image() {{
    lv_image_dsc_t image{{}};
    image.header.magic = LV_IMAGE_HEADER_MAGIC;
    image.header.cf = LV_COLOR_FORMAT_RGB565;
    image.header.w = 140;
    image.header.h = 130;
    image.header.stride = 280;
    image.data_size = sizeof(k{name}Pixels);
    image.data = k{name}Pixels;
    return image;
}}
constexpr auto k{name}Image = Make{name}Image();""")
        wav = tmp / f'{name.lower()}.wav'
        # Decode a contiguous real excerpt; peak-normalize to -7 dBFS and apply short fades.
        pcm = run(['ffmpeg','-v','error','-ss',str(start),'-i',str(ROOT/'originals'/sound),
            '-t',str(duration),'-ac','1','-ar','24000','-f','s16le','pipe:1'])
        samples = struct.unpack(f'<{len(pcm)//2}h',pcm)
        gain = (32767 * 10**(-7/20)) / max(abs(v) for v in samples)
        run(['ffmpeg','-v','error','-y','-ss',str(start),'-i',str(ROOT/'originals'/sound),
            '-t',str(duration),'-ac','1','-ar','24000','-af',
            f'volume={gain:.12f},afade=t=in:d=0.012,afade=t=out:st={duration-0.025}:d=0.025',
            '-map_metadata','-1','-c:a','pcm_s16le',str(wav)])
        ogg = tmp / f'{name.lower()}.ogg'
        run(['ffmpeg','-v','error','-y','-fflags','+bitexact','-i',str(wav),'-map_metadata','-1',
            '-ac','1','-ar','24000','-c:a','libopus','-b:a','24000','-vbr','off','-application','audio',
            '-frame_duration','60','-compression_level','10','-flags:a','+bitexact',
            '-fflags','+bitexact','-serial_offset','0','-metadata','copyright=CC0 1.0',str(ogg)])
        data = ogg.read_bytes(); packets = ogg_packets(data)
        assert packets[0][:8] == b'OpusHead' and packets[0][9] == 1
        assert struct.unpack_from('<I',packets[0],12)[0] == 24000
        assert max(map(len,packets)) <= 2048
        assert all(packet_duration_ms(p) == 60 for p in packets[2:])
        assert len(packets[2:]) * 60 <= 3000
        decoded = run(['ffmpeg','-v','error','-i',str(ogg),'-f','s16le','-ar','24000','pipe:1'])
        peak = max(abs(v) for v in struct.unpack(f'<{len(decoded)//2}h',decoded))/32768
        assert 0 < peak < 0.56
        parts.append(array(f'k{name}Sound',data))
        reports.append(dict(name=name,image_bytes=len(pixels),sound_bytes=len(data),
            excerpt_start=start,excerpt_seconds=duration,playback_ms=len(packets[2:])*60,
            decoded_peak=round(peak,5),ogg_sha256=hashlib.sha256(data).hexdigest()))
    parts += ['}  // namespace', 'const lv_image_dsc_t* GetImage(size_t index) {', '    switch (index) {']
    parts += [f'        case {i}: return &k{name}Image;' for i,(name,*_) in enumerate(ITEMS)]
    parts += ['        default: return nullptr;', '    }', '}',
              'std::string_view GetSound(size_t index) {', '    switch (index) {']
    parts += [f'        case {i}: return {{reinterpret_cast<const char*>(k{name}Sound), sizeof(k{name}Sound)}};' for i,(name,*_) in enumerate(ITEMS)]
    parts += ['        default: return {};', '    }', '}', '}  // namespace transport_game_assets','#endif','']
    return '\n'.join(parts), reports

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    with tempfile.TemporaryDirectory() as td:
        tmp=Path(td); source,reports=generate(tmp)
        for filename,content in [('transport_game_assets.h',HEADER),('transport_game_assets.cc',source)]:
            path=BOARD/filename
            if args.check:
                if not path.exists() or path.read_text()!=content: raise SystemExit(f'{filename} differs')
            else: path.write_text(content)
        if not args.check:
            import shutil
            for item in tmp.iterdir():
                if item.suffix in ('.ogg','.wav') or item.stem.islower(): shutil.copyfile(item,ROOT/'previews'/item.name)
            (ROOT/'validation.json').write_text(json.dumps(reports,indent=2)+'\n')
        print(json.dumps(reports,indent=2))
if __name__ == '__main__': main()
