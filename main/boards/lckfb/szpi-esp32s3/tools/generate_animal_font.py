#!/usr/bin/env python3
"""Create the offline UI's small OFL-licensed Chinese glyph subset.

Requires lv_font_conv 1.5.3 and NotoSansCJKsc-Regular.otf version 2.004.
Both are build-time inputs only; no network is used by this script.
"""

import argparse
from pathlib import Path
import subprocess
import tempfile

TEXT = "小猫小狗小鸭母鸡小牛小羊照片卡通动物朋友返回轻轻点一下听一听…休息一下吧和爸爸妈妈说说小动物家长长按再玩"
BOARD = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    parser.add_argument("--converter", default="lv_font_conv")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as temporary:
        output = Path(temporary) / "animal_game_font.c"
        subprocess.run([
            args.converter, "--font", str(args.font), "--symbols", "".join(sorted(set(TEXT))),
            "--size", "20", "--bpp", "4", "--format", "lvgl", "--no-compress",
            "--no-kerning", "--lv-include", "lvgl.h", "--lv-font-name", "animal_game_font",
            "-o", str(output),
        ], check=True)
        generated = output.read_text()
        # Replace machine-specific input paths in the converter banner.
        generated = generated[generated.index("#ifdef LV_LVGL_H_INCLUDE_SIMPLE"):]
        generated = (
            "/* Generated by tools/generate_animal_font.py; do not edit by hand.\n"
            " * Animal Game UI, derived from Noto Sans CJK SC Regular 2.004.\n"
            " * Original font copyright: (c) 2014-2021 Adobe.\n"
            " * Font license: licenses/animal_game_font-OFL.txt (SIL OFL 1.1).\n"
            " */\n#include \"sdkconfig.h\"\n#ifndef CONFIG_USE_EMOTE_MESSAGE_STYLE\n\n"
            + generated + "\n#endif  // !CONFIG_USE_EMOTE_MESSAGE_STYLE\n"
        )
        destination = BOARD / "animal_game_font.c"
        if args.check:
            if not destination.exists() or destination.read_text() != generated:
                raise SystemExit("Font differs; regenerate with the documented toolchain")
            print("Animal Game UI font matches")
        else:
            destination.write_text(generated)
            print(f"Wrote {destination.name}: {len(set(TEXT))} glyphs")


if __name__ == "__main__":
    main()
